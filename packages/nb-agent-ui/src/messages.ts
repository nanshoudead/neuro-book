const TABLES: Record<AgentLocale, Record<AgentTextKey, string>> = {"zh-CN": ZH, "en-US": EN};

type TextParams = Readonly<Record<string, string | number>>;

function fill(template: string, params: TextParams | undefined): string {
    if (params === undefined) return template;
    return template.replace(/\{(\w+)\}/gu, (placeholder, name: string) => (name in params ? String(params[name]) : placeholder));
}

/** 本包文字表里的一条，代入参数。 */
export function agentText(locale: AgentLocale, key: AgentTextKey, params?: TextParams): string {
    return fill(TABLES[locale][key], params);
}

/** 把一段界面文字按语言取成字符串。 */
export function textOf(text: ViewText, locale: AgentLocale): string {
    if (typeof text === "string") return text;
    if ("key" in text) return agentText(locale, text.key, text.params);
    return text[locale];
}

/** 宿主与插件写带参数的文字时用：两种语言各代入一次。 */
export function formatText(template: LocalizedText, params: TextParams): LocalizedText {
    return {"zh-CN": fill(template["zh-CN"], params), "en-US": fill(template["en-US"], params)};
}
