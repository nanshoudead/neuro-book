import {readFile} from "node:fs/promises";
import {gunzipSync} from "node:zlib";
const NB = "../../../../../packages/nb-story";
const T28 = "../../t28-graph-tiering";
const {buildBookIndex} = await import(`${NB}/src/core/book-index.ts`);
const {tiersAt} = await import(`${NB}/src/core/tiers.ts`);
const sample = JSON.parse(gunzipSync(await readFile(`${NB}/tests/fixtures/sample-100ch.json.gz`)).toString("utf8"));
const a = JSON.parse(await readFile(`${T28}/evidences/tiers-run-1.json`, "utf8")).tiers as Record<string, number>;
const b = JSON.parse(await readFile(`${T28}/evidences/tiers-run-2.json`, "utf8")).tiers as Record<string, number>;
const end = (d: any, ch: number) => ({chapter: ch, paragraph: d.sources.find((s: any) => s.chapter === ch).paragraphs.length});
const pct = (n: number, d: number) => `${(100 * n / Math.max(1, d)).toFixed(0)}%`;
const dist = (ts: number[]) => [1, 2, 3].map(t => pct(ts.filter(x => x === t).length, ts.length)).join("/");
function report(label: string, d: any, P: number, filter: (s: any) => boolean) {
  const t0 = performance.now();
  const index = buildBookIndex({id: "x", generation: "g"} as any, d);
  const t1 = performance.now();
  const table = tiersAt(index, end(d, P));
  const list = index.statements.filter((s: any) => s.at.chapter <= P && filter(s));
  const rs = list.map((s: any) => ({s, r: table.statement(s.id)!}));
  const t2 = performance.now();
  const ts = rs.map(x => x.r.tier);
  const evs = ["unknown", "none", "some", "strong"].map(e => `${e}:${pct(rs.filter(x => x.r.ev === e).length, rs.length)}`).join(" ");
  const frontier = rs.filter(x => x.s.at.chapter > P - 3);
  const lab = rs.filter(x => a[x.s.id] && b[x.s.id]);
  const exact = lab.filter(x => x.r.tier === a[x.s.id]).length;
  const hidden = lab.filter(x => x.r.tier === 3);
  const safe = hidden.filter(x => !(a[x.s.id] === 1 && b[x.s.id] === 1)).length;
  const t1s = lab.filter(x => x.r.tier === 1);
  const good1 = t1s.filter(x => !(a[x.s.id] === 3 && b[x.s.id] === 3)).length;
  const flags = ["unconfirmed", "foreshadow"].map(f => `${f}:${rs.filter(x => x.r.flag === f).length}`).join(" ");
  console.log(`${label} P=${P} n=${rs.length} 1/2/3=${dist(ts)} ev[${evs}] 最近3章 1/2/3=${dist(frontier.map(x => x.r.tier))} | 标注 n=${lab.length} 一致${pct(exact, lab.length)} 3级安全${pct(safe, hidden.length)}(${hidden.length}) 1级不误${pct(good1, t1s.length)}(${t1s.length}) ${flags} | index ${(t1 - t0).toFixed(0)}ms tiers ${(t2 - t1).toFixed(0)}ms`);
}
const withPrior = structuredClone(sample);
for (const s of withPrior.statements) if (a[s.id]) s.tier = a[s.id];
for (const P of [20, 50, 100]) report("样例·无先验", sample, P, () => true);
for (const P of [20, 50, 100]) report("样例·无先验·前20章", sample, P, (s: any) => s.at.chapter <= 20);
for (const P of [20, 100]) report("样例·先验run1·前20章", withPrior, P, (s: any) => s.at.chapter <= 20);
const xyj = JSON.parse(await readFile("../../../../../packages/nb-story/examples/journey-to-the-west/xiyouji-graph.json", "utf8"));
for (const P of [10, 30, 100]) report("西游记·无先验", xyj, P, () => true);
